#!/usr/bin/env node
// =============================================================================
// Tool retrieval eval — snapshot the built-in tool catalog
// =============================================================================
// Writes catalog.json: every built-in tool Nest can serve, with every built-in
// capability on, as { name, description, inputSchema } in the order MCP lists
// them. That is the set the eval scores against ("the real catalog": a chat
// account with everything enabled), and the frozen CI subset is keyed to it.
//
// The File System tools come from the reference filesystem server, which only
// lists them once its child process is up, so this spawns it on a temp folder
// (the same path test-mcp-capabilities.mjs drives) and stops it after.
// ask_user and update_plan are included, as chat-ui's session asks for them.
//
// Run again whenever a built-in tool's name, description or schema changes,
// then refreeze (run.mjs --freeze). test-retrieval-eval.mjs fails when this
// snapshot and the in-process providers disagree.
//
//   node scripts/retrieval-eval/build-catalog.mjs
// =============================================================================

import * as fs from 'node:fs'
import * as os from 'node:os'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { registerElectronStub } from '../electron-stub-hooks.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'redstart-retrieval-catalog-'))
process.env.REDSTART_TEST_USERDATA_DIR = tmp
registerElectronStub()
await import('../electron-stub.mjs')

const { fullCatalogConfig, catalogContext, toCatalogEntry } = await import('./lib.mjs')
const { activeToolCatalog } = await import('../../daemon/mcp-server.mjs')
const fsProvider = await import('../../daemon/filesystem-mcp-provider.mjs')

const fsRoot = path.join(tmp, 'fs-root')
fs.mkdirSync(fsRoot, { recursive: true })
const cfg = fullCatalogConfig(fsRoot)

try {
  await fsProvider.syncFilesystemProvider(cfg.fileSystem, path.join(tmp, 'logs'))
  if (!fsProvider.isFilesystemProviderReady()) throw new Error('the filesystem child did not become ready')
  const tools = activeToolCatalog(cfg, catalogContext()).map(toCatalogEntry)
  const out = path.join(here, 'catalog.json')
  fs.writeFileSync(out, `${JSON.stringify({ note: 'Generated by build-catalog.mjs. Do not edit by hand.', tools }, null, 2)}\n`)
  console.log(`${tools.length} tools -> ${path.relative(process.cwd(), out)}`)
  console.log(tools.map((t) => t.name).join(', '))
} finally {
  await fsProvider.syncFilesystemProvider({ enabled: false })
  fs.rmSync(tmp, { recursive: true, force: true })
}
